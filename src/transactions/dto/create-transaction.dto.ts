import { Type } from 'class-transformer';
import {
  IsDate,
  IsEnum,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsPositive,
  IsString,
  Length,
  Min,
} from 'class-validator';
import { TransactionStatus } from '../entities/enum/transactions-status.enum';
import { IncomeExpensive } from 'src/common/enums/income-expensive.enum';
import {
  DESCRIPTION_MAX_LENGTH,
  DESCRIPTION_MIN_LENGTH,
} from 'src/common/constants/validation.constants';

export class CreateTransactionDto {
  @IsNotEmpty()
  @IsInt()
  accountId: number;

  @IsNotEmpty()
  @IsInt()
  categoryId: number;

  /** Value in cents. E.g.: R$ 12,34 => 1234. */
  @IsNotEmpty()
  @IsInt()
  @IsPositive()
  value: number;

  @IsEnum(IncomeExpensive, {
    message: `Type must be one of the following: ${Object.values(IncomeExpensive).join(', ')}`,
  })
  type: IncomeExpensive;

  @IsEnum(TransactionStatus, {
    message: `Status must be one of the following: ${Object.values(TransactionStatus).join(', ')}`,
  })
  status: TransactionStatus;

  @IsNotEmpty()
  @IsInt()
  @Min(1)
  installment: number;

  @IsNotEmpty()
  @IsInt()
  @Min(1)
  amountInstallments: number;

  @IsOptional()
  @IsInt()
  destinationAcccountId?: number;

  /** Always generated by the server; anything sent by the client is ignored. */
  installmentsGroupId: string;

  @IsOptional()
  @IsString()
  @Length(DESCRIPTION_MIN_LENGTH, DESCRIPTION_MAX_LENGTH)
  description: string;

  @Type(() => Date)
  @IsDate()
  transactionDate: Date;
}
